// Screenshots of every screen, plus one real clean of a throwaway file.
import { _electron as electron } from 'playwright';
import fs from 'fs'; import os from 'os'; import path from 'path';
const probe = path.join(os.homedir(), 'Downloads', 'diskshaper-probe-setup.dmg');
fs.writeFileSync(probe, Buffer.alloc(3e6, 1));
const old = new Date(Date.now() - 30 * 864e5); fs.utimesSync(probe, old, old);
const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-test-')); // keeps test cleans out of the real freed total
const app = await electron.launch({ args: ['.'], env: { ...process.env, DISKSHAPER_USERDATA: userData } });
let w; for (let i = 0; i < 100 && !w; i++) { w = app.windows()[0]; if (!w) await new Promise(r => setTimeout(r, 200)); }
if (!w) w = await app.firstWindow();
const errs = []; w.on('pageerror', (e) => errs.push(e.message)); w.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await w.setViewportSize({ width: 1180, height: 780 });
await w.waitForTimeout(1200);
await w.screenshot({ path: 'shots/1-home.png' });
await w.click('#scanBtn');
await w.waitForTimeout(700);
await w.screenshot({ path: 'shots/2-scanning.png' });
await w.waitForSelector('#overview:not([hidden])', { timeout: 120000 });
await w.waitForTimeout(1500);
await w.screenshot({ path: 'shots/3-overview.png' });
await w.evaluate(() => document.querySelector('.stage').scrollTop = 500);
await w.waitForTimeout(600);
await w.screenshot({ path: 'shots/3b-overview-scrolled.png' });
await w.click('#seg button[data-g="gamers"]');
await w.waitForTimeout(900);
await w.screenshot({ path: 'shots/4-gaming.png' });
await w.click('.tile >> nth=0');
await w.waitForTimeout(1000);
await w.screenshot({ path: 'shots/5-detail-games.png' });
await w.click('#seg button[data-g="everyone"]');
await w.waitForTimeout(600);
await w.click('.tile:has-text("Duplicate photos")');
await w.waitForTimeout(1500);
await w.screenshot({ path: 'shots/6-detail-photos.png' });
await w.click('.d-back');
await w.waitForTimeout(500);
await w.click('.tile:has-text("Developer tool")');
await w.waitForTimeout(1500);
await w.screenshot({ path: 'shots/7-detail-dev.png' });
// clean only the probe
await w.click('.d-back'); await w.waitForTimeout(500);
await w.click('.tile:has-text("Old installers")'); await w.waitForTimeout(800);
const ok = await w.evaluate((probe) => { selected.clear(); selected.add(probe); renderResults(); return state.result.cats.some(c => c.items.some(i => i.path === probe)); }, probe);
await w.waitForTimeout(300);
await w.click('#cleanBtn');
await w.waitForSelector('#doneBg:not([hidden])');
await w.waitForTimeout(1400);
await w.screenshot({ path: 'shots/8-done.png' });
console.log('probe found:', ok, '| probe left Downloads:', !fs.existsSync(probe));
console.log('errors:', errs);
await app.close();
